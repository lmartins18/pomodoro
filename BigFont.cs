namespace Pomodoro;

static class BigFont
{
    public const int Height = 6;

    static readonly string[][] Digits =
    [
        [" █████╗ ", "██╔══██╗", "██║  ██║", "██║  ██║", "╚█████╔╝", " ╚════╝ "],
        ["   ██╗  ", "  ███║  ", "  ╚██║  ", "   ██║  ", "   ██║  ", "   ╚═╝  "],
        ["██████╗ ", "╚════██╗", " █████╔╝", "██╔═══╝ ", "███████╗", "╚══════╝"],
        ["██████╗ ", "╚════██╗", " █████╔╝", " ╚═══██╗", "██████╔╝", "╚═════╝ "],
        ["██╗  ██╗", "██║  ██║", "███████║", "╚════██║", "     ██║", "     ╚═╝"],
        ["███████╗", "██╔════╝", "███████╗", "╚════██║", "███████║", "╚══════╝"],
        [" ██████╗", "██╔════╝", "███████╗", "██╔══██║", "╚█████╔╝", " ╚════╝ "],
        ["███████╗", "╚════██║", "    ██╔╝", "   ██╔╝ ", "   ██║  ", "   ╚═╝  "],
        [" █████╗ ", "██╔══██╗", "╚█████╔╝", "██╔══██╗", "╚█████╔╝", " ╚════╝ "],
        [" █████╗ ", "██╔══██╗", "╚██████║", " ╚═══██║", " █████╔╝", " ╚════╝ "],
    ];

    static readonly string[] Colon = ["   ", "██╗", "╚═╝", "██╗", "╚═╝", "   "];

    public static string[] Render(string text)
    {
        var glyphs = text.Select(ch => ch == ':' ? Colon : Digits[ch - '0']).ToArray();
        return Enumerable.Range(0, Height).Select(row => string.Join(' ', glyphs.Select(g => g[row]))).ToArray();
    }

    public static bool IsShadow(char ch) => ch is not '█' and not ' ';
}
